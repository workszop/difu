#!/usr/bin/env node
// Pre-trains the toy model (toy.js) for each shape with the same settings the app uses live,
// and writes assets/toy-weights.js: the fallback for slow phones ("load pre-trained weights").
// Also records the loss per epoch and the share of points on the shape every PREVIEW_EVERY epochs,
// exactly as the live training in index.html does.
// Run: node tools/pretrain_toy.js
const fs = require('fs'), path = require('path');
const Toy = require('../toy.js');
const EPOCHS = 375, SEED = 1, PREVIEW_EVERY = 25, PREVIEW_N = 400, PREVIEW_SEED = 3;   // keep in sync with index.html
const lrAt = e => 1e-4 + (4e-3 - 1e-4) * 0.5 * (1 + Math.cos(Math.PI * e / EPOCHS));
const out = { epochs: EPOCHS, seed: SEED, previewEvery: PREVIEW_EVERY, previewN: PREVIEW_N, previewSeed: PREVIEW_SEED, params: Toy.N_PARAMS, shapes: {} };
for (const shape of ['heart', 'fish', 'q']) {
  const t0 = Date.now(), tr = Toy.createTrainer({ shape, seed: SEED }), losses = [], quality = [];
  const preview = e => quality.push([e, +Toy.quality(Toy.quickSample(tr.layers, PREVIEW_N, PREVIEW_SEED), shape).toFixed(3)]);
  preview(0);
  for (let e = 0; e < EPOCHS; e++) {
    losses.push(+tr.epoch(lrAt(e)).toFixed(4));
    if ((e + 1) % PREVIEW_EVERY === 0) preview(e + 1);
  }
  out.shapes[shape] = { weights: Toy.packWeights(tr.layers), losses, quality };
  console.log(shape, `${(Date.now() - t0) / 1000}s`, 'loss', losses[0], '->', losses.at(-1), 'on shape', quality[0][1], '->', quality.at(-1)[1]);
}
fs.writeFileSync(path.join(__dirname, '../assets/toy-weights.js'),
  '// Generated by tools/pretrain_toy.js - do not edit by hand\nwindow.TOY_PRETRAINED = ' + JSON.stringify(out) + ';\n');
