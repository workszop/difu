#!/usr/bin/env node
// Pre-trains the toy model (toy.js) for each shape with the same settings the app uses live,
// and writes assets/toy-weights.js: the fallback for slow phones ("load pre-trained weights").
// Run: node tools/pretrain_toy.js
const fs = require('fs'), path = require('path');
const Toy = require('../toy.js');
const EPOCHS = 600, SEED = 1;
const lrAt = e => 1e-4 + (4e-3 - 1e-4) * 0.5 * (1 + Math.cos(Math.PI * e / EPOCHS)); // keep in sync with index.html
const out = { epochs: EPOCHS, seed: SEED, params: Toy.N_PARAMS, shapes: {} };
for (const shape of ['heart', 'fish', 'q']) {
  const t0 = Date.now(), tr = Toy.createTrainer({ shape, seed: SEED }), losses = [];
  for (let e = 0; e < EPOCHS; e++) losses.push(+tr.epoch(lrAt(e)).toFixed(4));
  out.shapes[shape] = { weights: Toy.packWeights(tr.layers), losses };
  console.log(shape, `${(Date.now() - t0) / 1000}s`, 'loss', losses[0], '->', losses.at(-1));
}
fs.writeFileSync(path.join(__dirname, '../assets/toy-weights.js'),
  '// Generated by tools/pretrain_toy.js - do not edit by hand\nwindow.TOY_PRETRAINED = ' + JSON.stringify(out) + ';\n');
