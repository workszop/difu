#!/usr/bin/env python3
"""Pack the Colab output into the app's assets.

Input:  tools/out/assets/gen/  (unzipped diffusion_frames.zip from generate_frames.ipynb)
Output: assets/gen/<case>/cNN.avif, pNN.avif and assets/gen/cases.js

Noisy frames hardly compress as WebP (~40 KB each); AVIF keeps them visually identical at a
third of the size, which is what keeps the whole set under the ~15 MB budget.

Run:  python3 tools/pack_frames.py
"""
import json
import shutil
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools/out/assets/gen"
DST = ROOT / "assets/gen"
Q_NOISY, Q_PRED = 35, 50
BUDGET_MB = 15.0
# prompts shown in the app (the Colab run may contain more)
KEEP_PROMPTS = ["kot", "latarnia", "owoce"]


def load_manifest(path):
    s = path.read_text()
    return json.loads(s[s.index("{"): s.rindex("}") + 1])


def main():
    data = load_manifest(SRC / "cases.js")
    data["prompts"] = [p for p in data["prompts"] if p["id"] in KEEP_PROMPTS]
    data["cases"] = [c for c in data["cases"] if c["prompt_id"] in KEEP_PROMPTS]
    if DST.exists():
        shutil.rmtree(DST)
    DST.mkdir(parents=True)
    errors, total = [], 0
    for c in data["cases"]:
        n, src, dst = c["steps"], SRC / c["id"], DST / c["id"]
        dst.mkdir()
        names = [f"c{k:02d}" for k in range(n + 1)] + [f"p{k:02d}" for k in range(1, n + 1)]
        for name in names:
            f = src / f"{name}.webp"
            if not f.exists():
                errors.append(f"{c['id']}: missing {name}")
                continue
            out = dst / f"{name}.avif"
            Image.open(f).convert("RGB").save(out, "AVIF", quality=Q_NOISY if name[0] == "c" else Q_PRED)
            total += out.stat().st_size
        if len(c["alphabar"]) != n + 1 or c["alphabar"][-1] != 1.0:
            errors.append(f"{c['id']}: alphabar has {len(c['alphabar'])} values, want {n + 1} ending in 1.0")
        if not c["roughness"][0] > c["roughness"][1]:
            errors.append(f"{c['id']}: step 0 not rougher than the last step")
    mb = total / 1e6
    data.update(format="avif", quality={"noisy": Q_NOISY, "pred": Q_PRED}, total_mb=round(mb, 2))
    (DST / "cases.js").write_text(
        "// Generated by tools/pack_frames.py from tools/generate_frames.ipynb output - do not edit\n"
        "window.DIFFUSION_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(f"{len(data['cases'])} cases, {mb:.2f} MB (budget {BUDGET_MB})")
    if mb > BUDGET_MB:
        errors.append(f"over budget: {mb:.2f} MB")
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    print("all invariants OK")


if __name__ == "__main__":
    main()
